PATTERNS = []
for source, target in TEMPLATES:
    parts = re.split(r"(\{\w+\})", source)
    pattern = "".join(f"(?P<{part[1:-1]}>.+?)" if part.startswith("{") else re.escape(part) for part in parts)
    PATTERNS.append((re.compile(pattern, re.DOTALL), target))

def translate(text, language="zh_CN"):
    if language != "en" or isinstance(text, RawLog):
        return str(text)
    if text in EN:
        return EN[text]
    for pattern, target in PATTERNS:
        match = pattern.fullmatch(text)
        if match:
            values = match.groupdict()
            for key in ("label", "detail"):
                if key in values:
                    values[key] = translate(values[key], language)
            return target.format(**values)
    if "\n" in text:
        return "\n".join(translate(line, language) for line in text.split("\n"))
    return text
